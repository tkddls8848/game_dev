using ConceptPoCs;
using static ConceptPoCs.V;
namespace Redline;
public class Rules : IGame
{
    public State Start(Scenario d)=>new();
    public View Describe(State s, Scenario d)
    {
        if(s.Step==1)
        {
            string title=s.A==1 && s.C==1?"읽히지만 남지 않은 문장":s.B==1 && s.A==0?"작가가 다시 보낸 목소리":"아직 다듬을 수 있는 원고";
            return End(title,s.A==1 && s.C==1?"작가: 이해하기 쉬워졌네요. 그런데 이제 누구의 이야기인지 모르겠습니다. 다음 원고에는 틀릴 만한 문장을 쓰지 않았습니다.":s.B==1 && s.A==0?"작가: 끝 문장을 앞으로 옮기니 제가 왜 이 이야기를 썼는지 알겠어요. 어머니의 말투를 남겨 줘서 고맙습니다.":"작가: 몇 군데는 받아들였고, 지우신 문장은 돌려놓았습니다. 다시 읽어 주실 수 있을까요?",
                "문장 길이와 작가의 목소리는 같은 점수가 아닙니다.",S("삭제",s.A==1?"핵심 문장":"없음"),S("구성",s.B==1?"결말을 앞으로":"원래 순서"),S("표현",s.C==1?"평이함":"고유한 말투"));
        }
        return new("서윤의 초고 · 바다가 접히는 밤","독자가 상황을 빨리 이해하도록 원고를 편집하세요. 작가는 어머니의 마지막 말만큼은 남겨 달라고 요청했습니다. 원고 위의 붉은 편집 도구를 사용합니다.",
            "출판사: 첫 문단에 사건이 드러나야 합니다. 작가: 이상한 문장이지만, 어머니는 정말 그렇게 말했어요.",
            new[]{S("원고", "1차 교정"),S("핵심 문장",s.A==1?"삭제됨":"보존"),S("수정",s.A+s.B+s.C)},
            new[]{C("strike",s.A==0?"어머니의 문장 삭제":"삭제 취소","문장에 실제 삭제선을 긋습니다",s with{A=1-s.A}),
                  C("move",s.B==0?"마지막 문단을 앞으로":"문단 순서 복구","죽음의 사실을 먼저 밝힙니다",s with{B=1-s.B}),
                  C("replace",s.C==0?"낯선 표현을 평이하게":"원래 표현 복구","바다가 접혔다 → 해가 저물었다",s with{C=1-s.C}),
                  C("return","수정 원고 돌려보내기","작가가 받아들인 수정과 거절한 수정을 확인",s with{Step=1})});
    }
}
